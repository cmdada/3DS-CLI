static inline void fb_char(int x, int y, char c, u8 r, u8 g, u8 b, int scale) {
  if (c < 32 || c > 126) return;
  const unsigned char *gl = font8x8[(int)c - 32];
  for (int row = 0; row < 8; row++) {
    unsigned char bits = gl[row];
    for (int col = 0; col < 8; col++) {
      if (bits & (1 << col)) {
        if (scale == 1) {
          fb_pixel(x + col, y + row, r, g, b);
        } else {
          fb_fill(x + col*scale, y + row*scale, scale, scale, r, g, b);
        }
      }
    }
  }
}

static inline void fb_string(int x, int y, const char *s, u8 r, u8 g, u8 b, int scale) {
  while (*s) {
    fb_char(x, y, *s, r, g, b, scale);
    x += 8 * scale;
    s++;
  }
}

// Center a string horizontally within a given width
static inline void fb_string_centered(int x, int y, int w, const char *s,
                                      u8 r, u8 g, u8 b, int scale) {
  int slen = strlen(s);
  int tw = slen * 8 * scale;
  int ox = x + (w - tw) / 2;
  fb_string(ox, y, s, r, g, b, scale);
}

