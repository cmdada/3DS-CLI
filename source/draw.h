// 3DS bottom screen: 320x240 pixels, BGR8 format (3 bytes/pixel)
// Framebuffer is rotated 90 degrees:
//   screen pixel (x, y) -> offset = (x * 240 + (239 - y)) * 3

static u8 *g_fb = NULL;

static inline void fb_init(void) {
  g_fb = gfxGetFramebuffer(GFX_BOTTOM, GFX_LEFT, NULL, NULL);
}

static inline void fb_pixel(int x, int y, u8 r, u8 g, u8 b) {
  if (x < 0 || x >= 320 || y < 0 || y >= 240) return;
  u32 off = (x * 240 + (239 - y)) * 3;
  g_fb[off] = b; g_fb[off+1] = g; g_fb[off+2] = r;
}

static inline void fb_fill(int x0, int y0, int w, int h, u8 r, u8 g, u8 b) {
  for (int y = y0; y < y0 + h; y++)
    for (int x = x0; x < x0 + w; x++)
      fb_pixel(x, y, r, g, b);
}

static inline void fb_clear(u8 r, u8 g, u8 b) {
  fb_fill(0, 0, 320, 240, r, g, b);
}

// Horizontal/vertical lines (faster than fb_fill for 1px)
static inline void fb_hline(int x, int y, int w, u8 r, u8 g, u8 b) {
  fb_fill(x, y, w, 1, r, g, b);
}
static inline void fb_vline(int x, int y, int h, u8 r, u8 g, u8 b) {
  fb_fill(x, y, 1, h, r, g, b);
}

// Filled rounded rectangle (2px corner radius approximation)
static inline void fb_rrect(int x, int y, int w, int h, u8 r, u8 g, u8 b) {
  if (w < 5 || h < 5) { fb_fill(x, y, w, h, r, g, b); return; }
  fb_fill(x + 2, y,     w - 4, 1,     r, g, b);  // top edge
  fb_fill(x + 1, y + 1, w - 2, 1,     r, g, b);  // top-1
  fb_fill(x,     y + 2, w,     h - 4, r, g, b);  // middle body
  fb_fill(x + 1, y+h-2, w - 2, 1,     r, g, b);  // bot-1
  fb_fill(x + 2, y+h-1, w - 4, 1,     r, g, b);  // bot edge
}

// Rounded rectangle outline (1px border, 2px radius)
static inline void fb_rrect_border(int x, int y, int w, int h, u8 r, u8 g, u8 b) {
  fb_hline(x+2, y, w-4, r, g, b);
  fb_hline(x+2, y+h-1, w-4, r, g, b);
  fb_vline(x, y+2, h-4, r, g, b);
  fb_vline(x+w-1, y+2, h-4, r, g, b);
  fb_pixel(x+1, y+1, r, g, b);
  fb_pixel(x+w-2, y+1, r, g, b);
  fb_pixel(x+1, y+h-2, r, g, b);
  fb_pixel(x+w-2, y+h-2, r, g, b);
}

// 3D-style key: filled rounded rect with highlight on top, shadow on bottom
static inline void fb_key3d(int x, int y, int w, int h,
                            u8 fr, u8 fg, u8 fb_c,   // face color
                            u8 hr, u8 hg, u8 hb,     // highlight
                            u8 sr, u8 sg, u8 sb) {    // shadow
  // Shadow (bottom 2px)
  fb_rrect(x, y + h - 3, w, 3, sr, sg, sb);
  // Face
  fb_rrect(x, y, w, h - 2, fr, fg, fb_c);
  // Highlight (top 2px inside)
  fb_hline(x + 3, y + 1, w - 6, hr, hg, hb);
  fb_hline(x + 2, y + 2, w - 4, hr, hg, hb);
}

